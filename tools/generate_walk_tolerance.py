#!/usr/bin/env python3
"""Replay Lemma A's reduction chains with a signed error in each premise.

The source statements, rule instances, canon checks, coefficients and table
bindings come from src/LengthSeven/LemmaA. Every generated identity and bound
is checked by Lean. Run from the repository root with Python 3.
"""

import re
from pathlib import Path

source = Path("src/LengthSeven")
baseline = source / "LemmaA"
destination = source / "WalkTolerance"


def lean_header(imports):
    return """/- SPDX-License-Identifier: Apache-2.0
   Generated by tools/generate_walk_tolerance.py from the Lemma A proofs. -/
module

""" + "\n".join(f"public import {item}" for item in imports) + """

set_option autoImplicit false
set_option maxRecDepth 4000
set_option linter.unusedVariables false
@[expose] public section
noncomputable section
namespace AlbertSequential.LengthSeven.LemmaA.WalkTolerance

open AlbertSequential AlbertSequential.LengthSeven.LemmaA
open WalkForm ShortTableInput

"""


variables = """variable {V : Type*} [AddCommGroup V] [Module ℝ V]
  {W : WalkForm V} {τ : TraceData} {ε : ℝ}

"""
footer = "end AlbertSequential.LengthSeven.LemmaA.WalkTolerance\n"


def step_cost(kind, parameters):
    mapped = {"A": "0", "X": "x", "Y": "y", "Z": "z"}
    arguments = [mapped[p] for p in re.findall(r"\([qvsm] := \.([AXYZ])\)", parameters)]
    if kind == "R1":
        assert len(arguments) == 2
        return f"r1Cost τ {' '.join(arguments)}"
    if kind == "R2":
        assert len(arguments) == 3
        return f"stepR2Cost τ {' '.join(arguments)}"
    return {"L2": "r3Cost τ", "D": "3 / 2", "Y": "1"}[kind]


def walk_sources():
    original = (baseline / "Walks.lean").read_text()
    macro = original[original.index("set_option hygiene"):original.index("variable {V")]
    proofs = original[original.index("theorem walk_W01"):original.rindex("end Albert")]
    blocks = re.findall(
        r"^theorem (walk_\w+) \(h : UsedRules W τ\).*? :\n"
        r"    W.L (\[[^\n]*?\]) = ([^\n]+) := by\n"
        r"((?:[^\n]+\n)+)", proofs, flags=re.MULTILINE)
    assert len(blocks) == len(re.findall(r"^theorem walk_", proofs, re.MULTILINE))
    recipe = {}
    output = []
    for name, walk, value, body in blocks:
        recipe[name] = len(recipe)
        generated = []
        costs = {}
        combination = []
        for line in body.splitlines():
            if m := re.fullmatch(r"  have (k\d+) := (walk_\w+) h ([xyz] [xyz] [xyz]) .+", line):
                label, prev, indices = m.groups()
                costs[label] = f"{prev}Cost τ {indices}"
                generated.append(line)
            elif m := re.fullmatch(r"  have (s\d+) := step(R1|R2|L2|D|Y) (.+)", line):
                label, kind, parameters = m.groups()
                costs[label] = step_cost(kind, parameters)
                pre, args = parameters.split(" (h.", 1)
                args = " (h." + args
                if kind == "L2":
                    args, n = re.subn(r"\(h\.r3 _ _ _ (\(PL\.ord [^)]*\))\)", r"h \1", args)
                else:
                    args, n = re.subn(r"\(h\.inst x y z hxyz (\(.*?\)) \(by decide\)\)",
                                      r"h (cover_e3 x y z hxyz \1 (by decide))", args)
                assert n == 1
                generated.append(f"  have {label} := step{kind}Within (x := x) (y := y) (z := z) {pre}{args}")
            elif line.startswith("  linear_combination "):
                terms = line.removeprefix("  linear_combination ").split(" + ")
                for term in terms:
                    coefficient, label = re.fullmatch(r"\((.*)\) \* ([ks]\d+)", term).groups()
                    assert label in costs
                    combination.append((coefficient, label))
            else:
                assert line in ["  walk_nf", "  exact W.L_nil"]
        cost = " + ".join(f"|({k} : ℝ)| * ({costs[l]})" for k, l in combination) or "0"
        output.append(f"def {name}Cost (τ : TraceData) (x y z : Letter) : ℝ :=\n  {cost}\n")
        output.append(
            f"theorem {name} (h : ShortTableInput W τ ε) (x y z : Letter) (hxyz : IsOrderingBCD x y z) :\n"
            f"    Within (Real.sqrt ε) ({name}Cost τ x y z) (W.L {walk}) ({value}) := by")
        if not combination:
            assert name == "walk_W01"
            output.append("  simp [Within, walk_W01Cost, W.L_nil]\n")
            continue
        output.extend(generated)
        for _, label in combination:
            output.append(f"  obtain ⟨e{label}, eq{label}, b{label}⟩ := Within.defect {label}")
        bound = [f"((of_abs b{l}).scale ({k}))" for k, l in combination]
        combined = bound[0]
        for next_bound in bound[1:]:
            combined = f"({combined}.add {next_bound})"
        output.append(f"  apply finish_defect (by simpa [{name}Cost] using {combined})")
        output.append("  walk_nf")
        output.append("  linear_combination " + " + ".join(f"({k}) * eq{l}" for k, l in combination) + "\n")

    index = ",\n    ".join(f"{name}Cost τ x y z" for name in recipe)
    support = f"""
/-- Sum of the budgets of all finite reductions and all label assignments. -/
def caseCost (τ : TraceData) (x y z : Letter) : Fin {len(recipe)} → ℝ :=
  ![{index}]

/-- One budget for the entire 28-history Gram table. -/
def gramCost (τ : TraceData) : ℝ :=
  ∑ x : Letter, ∑ y : Letter, ∑ z : Letter, ∑ k : Fin {len(recipe)}, |caseCost τ x y z k|

theorem gramCost_nonneg (τ : TraceData) : 0 ≤ gramCost τ := by
  unfold gramCost
  positivity

theorem caseCost_le (τ : TraceData) (x y z : Letter) (k : Fin {len(recipe)}) :
    caseCost τ x y z k ≤ gramCost τ := by
  unfold gramCost
  exact (le_abs_self _).trans ((Finset.single_le_sum (fun i _ => abs_nonneg (caseCost τ x y z i)) (Finset.mem_univ k)).trans
    ((Finset.single_le_sum (fun j _ => Finset.sum_nonneg (fun i _ => abs_nonneg (caseCost τ x y j i))) (Finset.mem_univ z)).trans
    ((Finset.single_le_sum (fun q _ => Finset.sum_nonneg (fun j _ =>
      Finset.sum_nonneg (fun i _ => abs_nonneg (caseCost τ x q j i)))) (Finset.mem_univ y)).trans
    (Finset.single_le_sum (fun p _ => Finset.sum_nonneg (fun q _ =>
      Finset.sum_nonneg (fun j _ => Finset.sum_nonneg (fun i _ => abs_nonneg (caseCost τ p q j i))))) (Finset.mem_univ x)))))

"""
    local_lemmas = """private theorem of_abs {d C a : ℝ} (h : |a| ≤ C * d) : Within d C a 0 := by
  simpa only [Within, sub_zero] using h

private theorem finish_defect {d C a b e : ℝ} (h : Within d C e 0) (he : a = b + e) :
    Within d C a b := by
  simpa only [Within, he, add_sub_cancel_left, sub_zero] using h

"""
    (destination / "Chains.lean").write_text(
        lean_header(["LengthSeven.WalkToleranceSteps"]) + macro + local_lemmas + variables
        + "\n".join(output) + support + footer
    )
    return recipe


def gram_sources(recipe):
    for label in "ABCD":
        original = (baseline / f"Entries{label}.lean").read_text()
        macro = original[original.index("set_option hygiene"):original.index("variable {V")]
        blocks = re.findall(
            r"^theorem (gram_\d+_\d+) \(h : UsedRules W τ\) :\n"
            r"    (.+) = (gram28 τ \d+ \d+) := by\n"
            r"  rw \[(W.form_pathVec, L_eq_of_canon W \(b := \[[^\n]*\]\) \(by decide\)),\n"
            r"    (walk_\w+) h (\d \d \d) \(by decide\),\n"
            r"    (show .* from rfl)\]\n"
            r"  gram_nf", original, re.MULTILINE)
        assert len(blocks) == len(re.findall(r"^theorem gram_", original, re.MULTILINE))
        output = []
        for name, lhs, rhs, normal, walk, indices, show in blocks:
            output.append(
                f"theorem {name} (h : ShortTableInput W τ ε) :\n"
                f"    Within (Real.sqrt ε) (gramCost τ) ({lhs}) ({rhs}) := by\n"
                f"  rw [{normal},\n    {show}]\n"
                f"  apply (({walk} h {indices} (by decide)).widen (Real.sqrt_nonneg ε)\n"
                f"    (caseCost_le τ {indices} {recipe[walk]})).transport rfl rfl\n"
                f"  gram_nf\n")
        (destination / f"Entries{label}.lean").write_text(
            lean_header(["LengthSeven.WalkTolerance.Chains"]) + macro + variables + "\n".join(output) + "\n" + footer
        )

    main = (baseline / "Main.lean").read_text()
    main = main[main.index("theorem gram_sym"):main.index("/-- Lemma A from the interface")]
    main = re.sub(r"(W.form \(W.pathVec \(word28 \S+\)\) \(W.pathVec \(word28 \S+\)\)) = (gram28 τ \S+ \w+)",
                  r"Within (Real.sqrt ε) (gramCost τ) (\1) (\2)", main)
    main = main.replace("UsedRules W τ", "ShortTableInput W τ ε")
    main = main.replace("rw [W.symm, h, gram28_symm]", "rw [W.symm, gram28_symm]\n  exact h")
    main = main.replace("/-- **Lemma A** (lem:cer:gram28), rule form: the used rule instances fix all Gram entries. -/",
                        "/-- Entrywise error propagation through the original finite 28-history reduction. -/")
    main = main.replace("theorem lemmaA (", "theorem lemmaA_within (")
    (destination / "Main.lean").write_text(
        lean_header([f"LengthSeven.WalkTolerance.Entries{label}" for label in "ABCD"])
        + variables + main + footer
    )


if __name__ == "__main__":
    destination.mkdir(exist_ok=True)
    gram_sources(walk_sources())
